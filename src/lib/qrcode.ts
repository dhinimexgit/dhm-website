import QRCode from 'qrcode';
import CryptoJS from 'crypto-js';
import { db, storage } from './firebase';
import { 
  collection, 
  addDoc, 
  query, 
  orderBy, 
  getDocs, 
  Timestamp,
  doc,
  updateDoc,
  getDoc
} from 'firebase/firestore';
import { ref, uploadBytes, getDownloadURL } from 'firebase/storage';

// QR Code History Interface
export interface QRCodeHistory {
  id?: string;
  version: number;
  generatedBy: string;
  generatedAt: Date;
  storageUrl: string;
  qrContent: string;        // The URL that the QR links to
  securityHash: string;     // Unique hash for verification
  sessionSalt: string;      // Random salt for uniqueness
  isActive: boolean;
}

// Secret key for generating unique hashes (in production, this should be in environment variables)
const SECRET_KEY = 'DHM_SECURE_2003_MSRP_KEY';
const SALT = 'DhinimexSaltKey2025';

/**
 * The QR code displays plain text "Dhm-msrp-2003" when scanned.
 * 
 * The "complex algorithm" is in the TRACKING SYSTEM:
 * 1. Each generation creates a unique security hash
 * 2. The hash is derived from: timestamp + version + generator + random salt
 * 3. This hash is stored in the database for verification
 * 4. Even if someone copies the QR visually, we can verify if it was officially generated
 */

/**
 * Generate a unique security hash for tracking and verification
 * This hash proves this specific QR was generated by our system
 */
export function generateSecurityHash(version: number, generatedBy: string, timestamp: number, sessionSalt: string): string {
  const payload = {
    v: version,
    g: generatedBy,
    t: timestamp,
    s: sessionSalt,
    k: SECRET_KEY
  };
  
  // Create HMAC-SHA256 hash
  const hash = CryptoJS.HmacSHA256(JSON.stringify(payload), SECRET_KEY + SALT).toString();
  
  // Return first 32 characters for a shorter but still secure hash
  return hash.substring(0, 32);
}

/**
 * Generate a random session salt for uniqueness
 */
export function generateSessionSalt(): string {
  return CryptoJS.lib.WordArray.random(16).toString();
}

/**
 * Verify if a QR code generation record is authentic
 */
export function verifySecurityHash(history: QRCodeHistory): boolean {
  const timestamp = history.generatedAt.getTime();
  const expectedHash = generateSecurityHash(
    history.version,
    history.generatedBy,
    timestamp,
    history.sessionSalt
  );
  return expectedHash === history.securityHash;
}

/**
 * Generate QR code as data URL with unique visual pattern
 * By varying error correction level and mask pattern, each QR looks different
 * but scans to the same text
 */
export async function generateQRCodeDataURL(
  plainText: string, 
  version: number
): Promise<string> {
  // Cycle through error correction levels based on version
  const errorLevels: ('L' | 'M' | 'Q' | 'H')[] = ['L', 'M', 'Q', 'H'];
  const errorLevel = errorLevels[version % 4];
  
  // Cycle through mask patterns (0-7) based on version
  const maskPattern = (version % 8) as 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7;
  
  const options: QRCode.QRCodeToDataURLOptions = {
    errorCorrectionLevel: errorLevel,
    type: 'image/png',
    width: 400,
    margin: 2,
    maskPattern: maskPattern,
    color: {
      dark: '#2E388C', // Brand navy color
      light: '#FFFFFF'
    }
  };
  
  return await QRCode.toDataURL(plainText, options);
}

/**
 * Get the next version number
 */
export async function getNextVersion(): Promise<number> {
  const historyRef = collection(db, 'qr_codes');
  const q = query(historyRef, orderBy('version', 'desc'));
  const snapshot = await getDocs(q);
  
  if (snapshot.empty) {
    return 1;
  }
  
  const latestVersion = snapshot.docs[0].data().version;
  return latestVersion + 1;
}

/**
 * Save QR code to Firebase Storage and record history with security tracking
 */
export async function saveQRCode(
  dataUrl: string,
  qrContent: string,
  generatedBy: string,
  version: number,
  securityHash: string,
  sessionSalt: string
): Promise<QRCodeHistory> {
  // Convert data URL to blob
  const response = await fetch(dataUrl);
  const blob = await response.blob();
  
  // Create unique filename with security hash
  const filename = `qr-codes/dhm-msrp-v${version}-${securityHash.substring(0, 8)}.png`;
  const storageRef = ref(storage, filename);
  
  // Upload to Firebase Storage
  await uploadBytes(storageRef, blob);
  const storageUrl = await getDownloadURL(storageRef);
  
  // Deactivate previous active QR codes
  const historyRef = collection(db, 'qr_codes');
  const activeQuery = query(historyRef);
  const activeSnapshot = await getDocs(activeQuery);
  
  for (const docSnapshot of activeSnapshot.docs) {
    if (docSnapshot.data().isActive) {
      await updateDoc(doc(db, 'qr_codes', docSnapshot.id), { isActive: false });
    }
  }
  
  // Save history record with security tracking
  const historyData = {
    version,
    generatedBy,
    generatedAt: Timestamp.now(),
    storageUrl,
    qrContent,
    securityHash,
    sessionSalt,
    isActive: true
  };
  
  const docRef = await addDoc(historyRef, historyData);
  
  return {
    id: docRef.id,
    version,
    generatedBy,
    generatedAt: new Date(),
    storageUrl,
    qrContent,
    securityHash,
    sessionSalt,
    isActive: true
  };
}

/**
 * Get QR code history
 */
export async function getQRCodeHistory(): Promise<QRCodeHistory[]> {
  const historyRef = collection(db, 'qr_codes');
  const q = query(historyRef, orderBy('generatedAt', 'desc'));
  const snapshot = await getDocs(q);
  
  return snapshot.docs.map(doc => {
    const data = doc.data();
    return {
      id: doc.id,
      version: data.version,
      generatedBy: data.generatedBy,
      generatedAt: data.generatedAt.toDate(),
      storageUrl: data.storageUrl,
      qrContent: data.qrContent || 'Dhm-msrp-2003',
      securityHash: data.securityHash || '',
      sessionSalt: data.sessionSalt || '',
      isActive: data.isActive
    };
  });
}

/**
 * Get the currently active QR code
 */
export async function getActiveQRCode(): Promise<QRCodeHistory | null> {
  const historyRef = collection(db, 'qr_codes');
  const q = query(historyRef, orderBy('generatedAt', 'desc'));
  const snapshot = await getDocs(q);
  
  const activeDoc = snapshot.docs.find(doc => doc.data().isActive);
  
  if (!activeDoc) {
    return null;
  }
  
  const data = activeDoc.data();
  return {
    id: activeDoc.id,
    version: data.version,
    generatedBy: data.generatedBy,
    generatedAt: data.generatedAt.toDate(),
    storageUrl: data.storageUrl,
    qrContent: data.qrContent || 'Dhm-msrp-2003',
    securityHash: data.securityHash || '',
    sessionSalt: data.sessionSalt || '',
    isActive: data.isActive
  };
}


/**
 * Main function to generate a new QR code with full workflow
 * 
 * Each QR code is UNIQUE but displays the same text when scanned.
 * 
 * How it works:
 * - The visible text is always "Dhm-msrp-2003"
 * - Invisible zero-width Unicode characters are appended
 * - These change the QR pattern without affecting display
 * - Each generation has a unique pattern that can't be copied
 */
export async function generateNewQRCode(generatedBy: string): Promise<{
  qrCodeDataUrl: string;
  history: QRCodeHistory;
}> {
  // Get next version
  const version = await getNextVersion();
  
  // Generate unique security components
  const timestamp = Date.now();
  const sessionSalt = generateSessionSalt();
  const securityHash = generateSecurityHash(version, generatedBy, timestamp, sessionSalt);
  
  // QR links to verification page - user must enter PIN to see the message
  // This prevents easy copying since just scanning doesn't reveal the content
  const baseUrl = process.env.NEXT_PUBLIC_SITE_URL || 'https://verify-product.netlify.app';
  const qrContent = `${baseUrl}/verify-pin`;
  
  // Generate QR code with unique pattern based on version
  // Each version uses different error correction + mask pattern combination
  const qrCodeDataUrl = await generateQRCodeDataURL(qrContent, version);
  
  // Save to storage and database with full security tracking
  const history = await saveQRCode(
    qrCodeDataUrl,
    qrContent,
    generatedBy,
    version,
    securityHash,
    sessionSalt
  );
  
  return {
    qrCodeDataUrl,
    history
  };
}

